"""Build one Hermes config.yaml for an evaluation run from the E4 base and overlays.

    python3 evalcfg/build_config.py --arm defense --model e4b [--scenario asi06-2] \
        [--set memguard.timeout=45] [--out config.yaml]

Merge order: base.yaml -> arms/<arm>.yaml -> models/<model>.yaml -> scenarios/<scenario>.yaml ->
--set. Dicts merge key by key; a list or scalar from a later source replaces the earlier one.
The output starts with a comment naming its sources and the sha256 of the config body, which the
run manifest records. A value still set to TODO is refused (--allow-todo to inspect a draft).

Runs on the team server's Python 3.8 with PyYAML; no Hermes import.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import sys
from pathlib import Path
from typing import List, Optional, Tuple

import yaml

HERE = Path(__file__).resolve().parent


def deep_merge(base: dict, overlay: dict) -> dict:
    merged = copy.deepcopy(base)
    for key, value in overlay.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = copy.deepcopy(value)
    return merged


def parse_set(item: str) -> Tuple[List[str], object]:
    """``a.b.c=value`` -> (["a", "b", "c"], value parsed as YAML, so 30 is an int and [x] a list)."""
    path, sep, raw = item.partition("=")
    if not sep or not path.strip():
        raise ValueError(f"--set needs key.path=value, got {item!r}")
    return [part for part in path.strip().split(".")], yaml.safe_load(raw)


def apply_set(config: dict, path: List[str], value: object) -> dict:
    overlay: dict = {}
    node = overlay
    for part in path[:-1]:
        node = node.setdefault(part, {})
    node[path[-1]] = value
    return deep_merge(config, overlay)


def find_todo(node: object, path: str = "") -> List[str]:
    if isinstance(node, dict):
        return [hit for key, value in node.items() for hit in find_todo(value, f"{path}.{key}" if path else str(key))]
    if isinstance(node, list):
        return [hit for i, value in enumerate(node) for hit in find_todo(value, f"{path}[{i}]")]
    return [path] if node == "TODO" else []


def sources(arm: str, model: str, scenario: Optional[str], root: Path = HERE) -> List[Path]:
    files = [root / "base.yaml", root / "arms" / f"{arm}.yaml", root / "models" / f"{model}.yaml"]
    if scenario:
        files.append(root / "scenarios" / f"{scenario}.yaml")
    missing = [str(f) for f in files if not f.is_file()]
    if missing:
        raise FileNotFoundError(f"no such overlay: {', '.join(missing)}")
    return files


def build(arm: str, model: str, scenario: Optional[str] = None, sets: Optional[List[str]] = None,
          *, root: Path = HERE, allow_todo: bool = False) -> Tuple[dict, str, str]:
    """(config, config.yaml text with a provenance header, sha256 of the body)."""
    files = sources(arm, model, scenario, root)
    config: dict = {}
    for f in files:
        config = deep_merge(config, yaml.safe_load(f.read_text(encoding="utf-8")) or {})
    for item in sets or []:
        config = apply_set(config, *parse_set(item))
    todo = find_todo(config)
    if todo and not allow_todo:
        raise ValueError(f"still TODO: {', '.join(todo)}")
    body = yaml.safe_dump(config, sort_keys=True, allow_unicode=True, default_flow_style=False)
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    header = "".join([
        "# Generated by evalcfg/build_config.py - edit the overlays, not this file.\n",
        f"# sources: {', '.join(str(f.relative_to(root)) for f in files)}\n",
        *(f"# set: {item}\n" for item in sets or []),
        f"# config_sha256: {digest}\n",
    ])
    return config, header + body, digest


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--arm", required=True, choices=["stock", "defense"])
    parser.add_argument("--model", default="e4b", choices=sorted(p.stem for p in (HERE / "models").glob("*.yaml")))
    parser.add_argument("--scenario", choices=sorted(p.stem for p in (HERE / "scenarios").glob("*.yaml")))
    parser.add_argument("--set", dest="sets", action="append", default=[], metavar="KEY.PATH=VALUE")
    parser.add_argument("--out", help="write here instead of stdout")
    parser.add_argument("--allow-todo", action="store_true", help="print a config that still has TODO values")
    args = parser.parse_args(argv)
    try:
        _, text, digest = build(args.arm, args.model, args.scenario, args.sets, allow_todo=args.allow_todo)
    except (ValueError, FileNotFoundError) as exc:
        print(f"build_config: {exc}", file=sys.stderr)
        return 2
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(digest)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
